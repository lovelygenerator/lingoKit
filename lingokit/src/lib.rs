/// The translations generated by `lingokit-build`. Defined as `LOCALES` by [`include_locales!`].
#[derive(Debug)]
pub struct Locales {
    /// The locale used when no other matches, and for missing keys.
    pub default_lang: &'static str,
    /// Prefix of the environment variables (`<PREFIX>_LANG`, ...).
    pub env_prefix: &'static str,
    /// Locale → (file name, FTL source).
    pub resources: &'static [(&'static str, &'static [(&'static str, &'static str)])],
    /// Message IDs of the default locale (attributes as `id.attr`).
    pub ids: &'static [&'static str],
}

/// A message ID with its arguments, as returned by the generated `msg` functions and by [`LocalizedError::message`].
#[derive(Debug)]
pub struct Msg<'a> {
    /// The message ID (`id` or `id.attr`).
    pub id: &'static str,
    /// The Fluent arguments.
    pub args: Option<FluentArgs<'a>>,
}

impl<'a> Msg<'a> {
    /// A message without arguments.
    pub const fn new(id: &'static str) -> Self {
        Self { id, args: None }
    }

    /// A message with arguments.
    pub fn with_args(id: &'static str, args: FluentArgs<'a>) -> Self {
        Self { id, args: Some(args) }
    }
}

/// Includes the code generated by `lingokit-build`. Call it at the crate root (`lib.rs` / `main.rs`).
///
/// It defines `pub static LOCALES: lingokit::Locales` and `pub mod msg` with a typed function for
/// each message (`msg::err_not_found(path)`).
#[macro_export]
macro_rules! include_locales {
    () => {
        include!(concat!(env!("OUT_DIR"), "/lingokit_locales.rs"));
    };
}
