//! Localize [clap](https://docs.rs/clap) CLIs and [rmcp](https://docs.rs/rmcp) MCP servers with
//! [Fluent](https://projectfluent.org/): one set of `.ftl` files for help texts, clap errors,
//! MCP tool descriptions and your own messages.
//!
//! # Crates
//!
//! | Crate | Role |
//! |---|---|
//! | `lingokit` | Runtime: [`Localizer`], locale resolution, built-in messages. Features `clap`, `rmcp`, `derive` (default) |
//! | [`lingokit-build`](https://docs.rs/lingokit-build) | `build.rs` helper: checks the FTL files and generates typed accessors |
//! | [`lingokit-macros`](https://docs.rs/lingokit-macros) | `#[derive(LocalizedError)]` |
//!
//! # Usage
//!
//! ```toml
//! [dependencies]
//! lingokit = { version = "0.1", features = ["clap", "rmcp"] }
//!
//! [build-dependencies]
//! lingokit-build = "0.1"
//! ```
//!
//! ```ignore
//! // build.rs
//! fn main() {
//!     lingokit_build::Config::new("locales").generate();
//! }
//!
//! // lib.rs (at the crate root): defines `LOCALES` and the `msg` module
//! lingokit::include_locales!();
//!
//! // Errors: the fields become Fluent variables ($path)
//! #[derive(Debug, thiserror::Error, lingokit::LocalizedError)]
//! pub enum Error {
//!     #[error("not found: {}", path.display())]
//!     #[ftl("err-not-found")]
//!     NotFound { path: std::path::PathBuf },
//! }
//!
//! // CLI (feature `clap`): main.rs
//! fn main() -> std::process::ExitCode {
//!     let (cli, loc) = lingokit::clap::parse::<Cli>(&LOCALES);
//!     lingokit::clap::exit_code(&loc, run(cli, &loc))
//! }
//!
//! // MCP server (feature `rmcp`)
//! impl Server {
//!     fn new(loc: lingokit::Localizer) -> Self {
//!         let tool_router = lingokit::rmcp::localize_if_enabled(Self::tool_router(), &loc);
//!         Self { loc, tool_router }
//!     }
//! }
//! ```
//!
//! # Locale
//!
//! The display language is chosen from `--lang` (CLI only), `<PREFIX>_LANG`, `LC_ALL`,
//! `LC_MESSAGES`, `LANG`, then the default locale. See [`locale`].

